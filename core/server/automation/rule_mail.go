package automation

import (
	"net/url"

	"github.com/pocketbase/pocketbase/core"
)

// The headers every rule send carries, core's and a package's alike, so one
// deployment marks and recognizes its rule mail the same way everywhere.
const (
	// AutoSubmittedHeader (RFC 3834) tells a well-behaved receiver not to
	// answer the message.
	AutoSubmittedHeader = "Auto-Submitted"
	// LoopHeader lets a deployment know its own rule mail when it comes back,
	// even after a relay drops Auto-Submitted.
	LoopHeader = "X-TinyCld-Loop"
)

// The Auto-Submitted values a rule send uses.
const (
	AutoGenerated = "auto-generated"
	AutoForwarded = "auto-forwarded"
)

// RuleMailHeaders are the headers a rule send carries: Auto-Submitted with
// kind (AutoGenerated or AutoForwarded), and LoopHeader with the deployment's
// web host.
func RuleMailHeaders(app core.App, kind string) map[string]string {
	return map[string]string{
		AutoSubmittedHeader: kind,
		LoopHeader:          ruleMailLoopHost(app),
	}
}

// ruleMailLoopHost is the deployment's web host, from the app settings, or
// "tinycld" when none is set. It tells a reader which deployment sent the mail.
func ruleMailLoopHost(app core.App) string {
	if u, err := url.Parse(app.Settings().Meta.AppURL); err == nil && u.Hostname() != "" {
		return u.Hostname()
	}
	return "tinycld"
}
