import * as fs from 'node:fs'
import * as path from 'node:path'
import { isRelativeHelpRef, normalizeHelpImageRef } from '../core/lib/help/images'

export interface Frontmatter {
    title: string
    summary: string
    tags: string[]
    order: number | null
    /**
     * The system_settings namespace this topic documents (e.g. `mail.`).
     *
     * A topic that explains how to configure a setting is wrong on a deployment
     * whose operator owns that setting — it walks the reader to a screen that
     * is not there. Declaring the namespace hides the topic exactly where the
     * matching settings panel is hidden. Omit it and the topic always shows.
     */
    keyPrefix: string | null
    body: string
}

// Minimal YAML frontmatter parser for help docs (title/summary/tags/order).
export function parseFrontmatter(raw: string): Frontmatter {
    const match = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/)
    if (!match) {
        return { title: '', summary: '', tags: [], order: null, keyPrefix: null, body: raw }
    }
    const [, head, body] = match
    let title = ''
    let summary = ''
    let tags: string[] = []
    let order: number | null = null
    let keyPrefix: string | null = null
    for (const line of head.split('\n')) {
        const kv = line.match(/^(\w+):\s*(.*)$/)
        if (!kv) continue
        const [, key, valRaw] = kv
        const val = valRaw.trim()
        if (key === 'title') title = stripQuotes(val)
        else if (key === 'summary') summary = stripQuotes(val)
        else if (key === 'order') order = val === '' ? null : Number(val)
        else if (key === 'tags') tags = parseInlineArray(val)
        else if (key === 'keyPrefix') keyPrefix = val === '' ? null : stripQuotes(val)
    }
    return { title, summary, tags, order, keyPrefix, body }
}

function stripQuotes(s: string): string {
    return s.replace(/^["']|["']$/g, '')
}

// Parse `[a, "b c", d]` → ['a','b c','d'].
function parseInlineArray(s: string): string[] {
    const inner = s.replace(/^\[|\]$/g, '').trim()
    if (!inner) return []
    return inner
        .split(',')
        .map(t => stripQuotes(t.trim()))
        .filter(Boolean)
}

export interface HelpTopicInput {
    topicId: string
    frontmatter: Frontmatter
}
export interface HelpImageInput {
    /** Path relative to the package's help/ dir, posix separators. */
    key: string
    /** Absolute path of the file on disk. */
    file: string
}
export interface HelpGroupInput {
    packageName: string
    pkgSlug: string
    topics: HelpTopicInput[]
    images: HelpImageInput[]
}

// Metro's default assetExts cover these on every platform.
export const HELP_IMAGE_EXTENSIONS = ['.png', '.jpg', '.jpeg', '.webp', '.gif']

export function collectHelpImages(helpDir: string): HelpImageInput[] {
    const images: HelpImageInput[] = []
    const walk = (dir: string) => {
        for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
            const file = path.join(dir, entry.name)
            if (entry.isDirectory()) walk(file)
            else if (HELP_IMAGE_EXTENSIONS.includes(path.extname(entry.name).toLowerCase())) {
                const key = path.relative(helpDir, file).split(path.sep).join('/')
                images.push({ key, file })
            }
        }
    }
    walk(helpDir)
    return images.sort((a, b) => a.key.localeCompare(b.key))
}

const IMAGE_REF = /!\[[^\]]*\]\(\s*<?([^)\s>]+)>?/g

/** Relative image refs in a topic body, as authored. */
export function helpImageRefs(body: string): string[] {
    return [...body.matchAll(IMAGE_REF)].map(m => m[1]).filter(isRelativeHelpRef)
}

/** Fails generation on a ref that is missing or climbs out of help/. */
export function validateHelpImages(group: HelpGroupInput): void {
    const shipped = new Set(group.images.map(i => i.key))
    for (const topic of group.topics) {
        for (const ref of helpImageRefs(topic.frontmatter.body)) {
            const where = `help topic ${group.pkgSlug}:${topic.topicId}`
            const key = normalizeHelpImageRef(ref)
            if (key === null) {
                throw new Error(`${where} references "${ref}", which must not contain ".."`)
            }
            if (!shipped.has(key)) {
                throw new Error(`${where} references missing image "${ref}" (expected help/${key})`)
            }
        }
    }
}

export function buildHelpSource(groups: HelpGroupInput[], generatedDir: string): string {
    const lines: string[] = [
        '// Auto-generated by app/scripts/generate.ts — do not edit',
        '',
        'export interface HelpTopicEntry {',
        '    id: string',
        '    pkgSlug: string',
        '    topicId: string',
        '    title: string',
        '    summary: string',
        '    tags: string[]',
        '    keyPrefix?: string',
        '    body: string',
        '}',
        '',
        'export interface HelpGroup {',
        '    packageName: string',
        '    pkgSlug: string',
        '    topics: HelpTopicEntry[]',
        '}',
        '',
        'export const packageHelp: HelpGroup[] = [',
    ]
    for (const g of groups) {
        const sorted = [...g.topics].sort((a, b) => {
            const ao = a.frontmatter.order
            const bo = b.frontmatter.order
            if (ao != null && bo != null) return ao - bo
            if (ao != null) return -1
            if (bo != null) return 1
            return a.topicId.localeCompare(b.topicId)
        })
        lines.push('    {')
        lines.push(`        packageName: ${JSON.stringify(g.packageName)},`)
        lines.push(`        pkgSlug: ${JSON.stringify(g.pkgSlug)},`)
        lines.push('        topics: [')
        for (const t of sorted) {
            const entry = {
                id: `${g.pkgSlug}:${t.topicId}`,
                pkgSlug: g.pkgSlug,
                topicId: t.topicId,
                title: t.frontmatter.title,
                summary: t.frontmatter.summary,
                tags: t.frontmatter.tags,
                // Emitted only when declared, so a topic that opts out stays
                // byte-identical to what it generated before.
                ...(t.frontmatter.keyPrefix ? { keyPrefix: t.frontmatter.keyPrefix } : {}),
                body: t.frontmatter.body,
            }
            lines.push(`            ${JSON.stringify(entry)},`)
        }
        lines.push('        ],')
        lines.push('    },')
    }
    lines.push(']')
    lines.push('')
    lines.push('// Metro bundles each file as a static asset: an asset id on native, a')
    lines.push('// { uri } object (or bare path) on web. Keys are "<pkgSlug>/<path under')
    lines.push('// help/>" and resolve through core/lib/help/images.')
    lines.push('export const helpImages: Record<string, number | string | { uri: string }> = {')
    for (const g of groups) {
        for (const image of g.images) {
            const rel = path.relative(generatedDir, image.file).split(path.sep).join('/')
            lines.push(
                `    ${JSON.stringify(`${g.pkgSlug}/${image.key}`)}: require(${JSON.stringify(rel)}),`
            )
        }
    }
    lines.push('}')
    lines.push('')
    return lines.join('\n')
}
